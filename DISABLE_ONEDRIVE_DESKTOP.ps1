# Disable OneDrive Desktop Sync
# This makes your Desktop go back to the local folder only

Write-Host "========================================" -ForegroundColor Cyan
Write-Host "DISABLE ONEDRIVE DESKTOP SYNC" -ForegroundColor Cyan
Write-Host "========================================" -ForegroundColor Cyan
Write-Host ""
Write-Host "Follow these steps:" -ForegroundColor Yellow
Write-Host ""
Write-Host "1. Right-click the OneDrive cloud icon in your system tray" -ForegroundColor White
Write-Host "   (bottom right corner near the clock)" -ForegroundColor Gray
Write-Host ""
Write-Host "2. Click 'Settings'" -ForegroundColor White
Write-Host ""
Write-Host "3. Go to 'Backup' tab" -ForegroundColor White
Write-Host ""
Write-Host "4. Click 'Manage backup'" -ForegroundColor White
Write-Host ""
Write-Host "5. Turn OFF the toggle for 'Desktop'" -ForegroundColor White
Write-Host ""
Write-Host "6. Click 'Save changes'" -ForegroundColor White
Write-Host ""
Write-Host "7. Wait a few minutes for files to move back to local Desktop" -ForegroundColor White
Write-Host ""
Write-Host "Done! You'll have only ONE Desktop folder." -ForegroundColor Green
Write-Host ""
pause
